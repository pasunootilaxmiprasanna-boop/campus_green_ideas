require('dotenv').config();
const path = require('path');
const express = require('express');
const helmet = require('helmet');
const rateLimit = require('express-rate-limit');
const authRoutes = require('./routes/auth');
const ideaRoutes = require('./routes/ideas');
require('./supabase');

const app = express();
const port = Number(process.env.PORT)||3000;
app.disable('x-powered-by');
app.use(helmet({crossOriginResourcePolicy:{policy:'same-origin'}}));
app.use(express.json({limit:'20kb'}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false,message:{error:'Too many authentication attempts. Please try again later.'}}));
app.use('/api',rateLimit({windowMs:60*1000,limit:120,standardHeaders:true,legacyHeaders:false,message:{error:'Too many requests. Please slow down.'}}));
app.get('/api/health',(req,res)=>res.json({status:'ok',application:'Campus Green Ideas Board',time:new Date().toISOString()}));
app.use('/api/auth',authRoutes);
app.use('/api/ideas',ideaRoutes);
app.use(express.static(path.join(__dirname,'..','frontend')));
app.get('/{*splat}',(req,res,next)=>{if(req.path.startsWith('/api/'))return res.status(404).json({error:'API endpoint not found.'});res.sendFile(path.join(__dirname,'..','frontend','index.html'),err=>{if(err)next(err);});});
app.use((err,req,res,next)=>{console.error('Request error:',err.message);if(res.headersSent)return next(err);res.status(500).json({error:'Unexpected server error. Please try again.'});});
app.listen(port,()=>console.log(`Campus Green Ideas Board running at http://localhost:${port}`));